import fs from 'node:fs';
import path from 'node:path';
import {createHash, randomUUID} from 'node:crypto';
import {performance} from 'node:perf_hooks';
import {DesignRecords} from './design-records.mjs';
import {DesignAssembly} from './design-assembly.mjs';
import {UxContributions} from './ux-contributions.mjs';
import {validateUxSpec} from './ux-design.mjs';
import {canonicalPublicationJson} from './product-publication-payload.mjs';

const stores = new Map();

/** Identifies immutable input without asking an author to compute bookkeeping.
 * @param {unknown} value - JSON input.
 * @returns {string} - Content identity.
 */
function hash(value) {
	return createHash('sha256').update(canonicalPublicationJson(value)).digest('hex');
}

/** Rejects linked scratch entries; all names below are generated by the store.
 * @param {string} target - Owned scratch entry.
 * @returns {string} - Safe entry path.
 */
function unlinked(target) {
	if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink())
		throw new Error('Linked contribution store entry');
	return target;
}

/** Publishes one immutable journal entry atomically.
 * @param {string} target - Store-generated path.
 * @param {object} value - Complete journal entry.
 * @returns {number} - Written byte count.
 */
function write(target, value) {
	unlinked(target);
	if (fs.existsSync(target)) throw new Error('Contribution journal changed; reopen before retrying');
	const temporary = `${target}.${randomUUID()}.pending`;
	const bytes = `${canonicalPublicationJson(value)}\n`;
	try {
		fs.writeFileSync(temporary, bytes, {flag: 'wx'});
		fs.renameSync(temporary, target);
	} finally {
		if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
	}
	return Buffer.byteLength(bytes);
}

/** Provides an actionable repair without discarding usable siblings.
 * @param {string} reference - Unit or batch identity.
 * @param {string} reason - Observed problem.
 * @returns {DesignRecordIssue} - Repair notice.
 */
function issue(reference, reason) {
	return {
		reference,
		reason,
		remedy: 'Repair this contribution using the current revision and a new batchId; reuse accepted batches.',
	};
}

/** Replays a saved accepted batch into the in-memory index once at startup.
 * @param {object} state - Resident store.
 * @param {object} entry - Immutable journal record.
 * @returns {void}
 */
function replay(state, entry) {
	if (entry.kind === 'batch') {
		for (const group of entry.groups) {
			const unit = state.units.get(group.reference) ?? UxContributions.empty(group.reference);
			for (const change of group.changes) UxContributions.apply(unit, change);
			state.units.set(group.reference, unit);
			state.revisions.set(group.reference, group.revision);
		}
		state.batches.set(entry.batchId, {digest: entry.digest, receipt: entry.receipt});
	} else if (entry.kind === 'finish') {
		for (const item of entry.saved) state.materialized.set(item.recordKey, item.digest);
	} else throw new Error('Unknown contribution journal entry');
}

/** Opens a bound baseline and replays durable contributions only once per process.
 * @param {string} store - Existing UX unit store.
 * @returns {object} - Resident contribution state.
 */
function open(store) {
	const root = path.resolve(store);
	if (stores.has(root)) return stores.get(root);
	const header = DesignRecords.read(root, []).header;
	if (header.stage !== 'ux') throw new Error('Contributions currently support UX only');
	const directory = unlinked(`${root}.contributions`);
	fs.mkdirSync(directory, {recursive: true});
	const baselinePath = unlinked(path.join(directory, 'baseline.json'));
	if (!fs.existsSync(baselinePath)) {
		const initial = DesignRecords.read(root);
		if (initial.issues.length)
			throw new Error('Repair baseline unit-store issues before contribution initialization');
		write(baselinePath, {format: 'ux-contributions/1', ...initial});
	}
	const baseline = JSON.parse(fs.readFileSync(baselinePath, 'utf8'));
	if (baseline.format !== 'ux-contributions/1' || hash(baseline.header) !== hash(header))
		throw new Error('Contribution baseline binding differs');
	const state = {
		root,
		directory,
		units: new Map(),
		revisions: new Map(Object.entries(baseline.identities)),
		materialized: new Map(Object.entries(baseline.identities)),
		batches: new Map(),
		sequence: 0,
	};
	for (const record of baseline.records)
		state.units.set(`${record.kind}:${record.id}`, UxContributions.decode(record));
	for (const name of fs
		.readdirSync(directory)
		.filter((name) => /^\d{8}\.json$/.test(name))
		.sort()) {
		if (Number(name.slice(0, 8)) !== state.sequence + 1) throw new Error('Contribution journal has a gap');
		replay(state, JSON.parse(fs.readFileSync(unlinked(path.join(directory, name)), 'utf8')));
		state.sequence++;
	}
	stores.set(root, state);
	return state;
}

/** Appends one journal entry; same-server synchronous operations cannot interleave.
 * @param {object} state - Resident state.
 * @param {object} entry - Complete entry.
 * @returns {number} - Durable bytes.
 */
function append(state, entry) {
	const bytes = write(path.join(state.directory, `${String(state.sequence + 1).padStart(8, '0')}.json`), entry);
	state.sequence++;
	return bytes;
}

/** Checks exact selected identities before reading or writing scratch units.
 * @param {string[]} references - Explicit assigned references.
 * @returns {string[]} - Unique validated references.
 */
function select(references) {
	if (!Array.isArray(references)) throw new Error('Explicit unit references are required');
	for (const reference of references) UxContributions.empty(reference);
	return [...new Set(references)];
}

/** Derives flow-to-element dependencies from authored ownership once at finish.
 * @param {DesignRecord[]} records - Authoring units.
 * @returns {Map<string, string[]>} - Mechanical owner dependencies by flow.
 */
function flowDependencies(records) {
	const owners = new Map();
	for (const record of records)
		if (record.kind === 'element')
			for (const [catalog, kind] of [
				['surfaces', 'surface'],
				['components', 'component'],
			])
				for (const item of record.data.catalogs?.[catalog]?.values ?? [])
					owners.set(`ux:${kind}:${item.id}`, `element:${record.id}`);
	return new Map(
		records
			.filter((record) => record.kind === 'flow')
			.map((record) => {
				const owner = owners.get(record.data.elementRef);
				return [`flow:${record.id}`, owner ? [owner] : []];
			}),
	);
}

/** Encodes working units and supplies their mechanical owner dependencies.
 * @param {object} state - Resident units.
 * @returns {DesignRecord[]} - Existing authoring envelopes.
 */
function materialize(state) {
	const records = [...state.units.values()].map((unit) => UxContributions.encode(unit));
	const dependencies = flowDependencies(records);
	for (const record of records)
		if (record.kind === 'flow') record.dependencies = dependencies.get(`flow:${record.id}`);
	return records;
}

/** Durable incremental UX authoring; canonical records are materialized only at finish. */
export const DesignContributions = {
	/** Returns opaque revisions and lightweight identities for selected assigned units.
	 * This initializes a scratch baseline, so the operation is classified as a write.
	 * @param {string} store - Bound UX store.
	 * @param {string[]} references - Assigned units, including not-yet-created units.
	 * @returns {object} - Revisions and record identities without content.
	 */
	status(store, references) {
		const selected = select(references),
			state = open(store);
		return {
			units: selected.map((reference) => ({
				reference,
				revision: state.revisions.get(reference) ?? null,
				collections: state.units.has(reference) ? UxContributions.identities(state.units.get(reference)) : {},
			})),
			batchCount: state.batches.size,
		};
	},

	/** Saves independent per-unit groups, keeping valid siblings when one group fails.
	 * All changes to one unit in a batch are atomic. Interdependent cross-unit edits
	 * may remain partial until finish reports reference readiness.
	 * @param {string} store - Bound UX store.
	 * @param {object} input - Batch ID, prior revisions and semantic changes.
	 * @returns {object} - Compact durable receipt and targeted repair notices.
	 */
	contribute(store, input) {
		const started = performance.now();
		if (typeof input.batchId !== 'string' || !/^[a-zA-Z0-9._-]{1,160}$/.test(input.batchId))
			throw new Error('Invalid batchId');
		if (!Array.isArray(input.changes) || !input.changes.length)
			throw new Error('A nonempty changes list is required');
		if (!input.base || typeof input.base !== 'object' || Array.isArray(input.base))
			throw new Error('Prior revisions are required');
		select(input.changes.map((change) => change.unit));
		const state = open(store),
			digest = hash({base: input.base, changes: input.changes});
		const previous = state.batches.get(input.batchId);
		if (previous) {
			if (previous.digest !== digest) throw new Error('batchId already exists with different content');
			return {...previous.receipt, reused: true};
		}
		const grouped = new Map();
		for (const change of input.changes) {
			if (!grouped.has(change.unit)) grouped.set(change.unit, []);
			grouped.get(change.unit).push(change);
		}
		const groups = [],
			issues = [],
			candidates = new Map();
		for (const [reference, changes] of grouped) {
			try {
				const currentRevision = state.revisions.get(reference) ?? null;
				if (!Object.hasOwn(input.base, reference) || input.base[reference] !== currentRevision)
					throw new Error(`Stale revision; current revision is ${currentRevision}`);
				const unit = structuredClone(state.units.get(reference) ?? UxContributions.empty(reference));
				for (const change of changes) UxContributions.apply(unit, change);
				const revision = hash({previous: currentRevision, batch: input.batchId, changes});
				groups.push({reference, changes, revision});
				candidates.set(reference, unit);
			} catch (error) {
				issues.push(issue(reference, error.message));
			}
		}
		const receipt = {
			batchId: input.batchId,
			reused: false,
			accepted: groups.map(({reference, revision, changes}) => ({reference, revision, changes: changes.length})),
			issues,
			pending: 'Required fields and references are checked at units.finish.',
			preparationMs: performance.now() - started,
		};
		const journalBytes = append(state, {kind: 'batch', batchId: input.batchId, digest, groups, receipt});
		for (const [reference, unit] of candidates) state.units.set(reference, unit);
		for (const group of groups) state.revisions.set(group.reference, group.revision);
		state.batches.set(input.batchId, {digest, receipt});
		return {...receipt, journalBytes, elapsedMs: performance.now() - started};
	},

	/** Materializes selected units once without another model-generated combined payload.
	 * Missing meaning remains saved and receives a repair notice; semantic approval
	 * and canonical promotion remain separate parent-owned operations.
	 * @param {string} store - Bound UX store.
	 * @param {string[]} references - Units completed by this assignment.
	 * @returns {object} - Saved unit identities, structural readiness and timings.
	 */
	finish(store, references) {
		const started = performance.now(),
			selected = select(references),
			state = open(store);
		const saved = [],
			issues = [];
		const records = materialize(state),
			indexed = new Map(records.map((record) => [`${record.kind}:${record.id}`, record]));
		for (const reference of selected) {
			try {
				if (!state.units.has(reference)) throw new Error('Unit has not been contributed');
				const record = indexed.get(reference);
				saved.push(DesignRecords.put(store, record, state.materialized.get(reference) ?? null));
			} catch (error) {
				issues.push(issue(reference, error.message));
			}
		}
		append(state, {kind: 'finish', saved});
		for (const item of saved) state.materialized.set(item.recordKey, item.digest);
		const persisted = DesignRecords.read(store);
		issues.push(...persisted.issues);
		const dependencies = flowDependencies(persisted.records);
		for (const record of persisted.records)
			if (
				record.kind === 'flow' &&
				hash(record.dependencies ?? []) !== hash(dependencies.get(`flow:${record.id}`))
			)
				issues.push(
					issue(
						`flow:${record.id}`,
						'Element ownership changed; finish this flow after its referenced element is materialized.',
					),
				);
		const assembly = DesignAssembly.ux(persisted.records);
		issues.push(...assembly.issues);
		if (assembly.document) {
			try {
				validateUxSpec(assembly.document);
			} catch (error) {
				issues.push(issue('ux-document', error.message));
			}
		}
		return {
			status: issues.length ? 'needs-repair' : 'structurally-ready',
			saved,
			issues,
			approval: 'unreviewed',
			batchCount: state.batches.size,
			elapsedMs: performance.now() - started,
		};
	},

	/** Releases resident indexes; the next call resumes from the durable baseline/journal.
	 * @param {string} store - Bound UX store.
	 * @returns {void}
	 */
	close(store) {
		stores.delete(path.resolve(store));
	},
};
