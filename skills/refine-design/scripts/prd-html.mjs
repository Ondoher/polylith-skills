function assertSafeOutputPath(outputRoot, relativePath) {
    const root = path.resolve(outputRoot);
    const target = path.resolve(root, relativePath);
    if (target !== root && !target.startsWith(`${root}${path.sep}`)) fail(`Output escapes destination: ${relativePath}`);
    if (fs.existsSync(root) && fs.lstatSync(root).isSymbolicLink()) fail(`Refusing linked output root: ${root}`);
    let current = root;
    for (const part of path.relative(root, target).split(path.sep).slice(0, -1)) {
        current = path.join(current, part);
        if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) fail(`Refusing linked output path: ${current}`);
    }
    if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) fail(`Refusing linked output file: ${target}`);
    return target;
}

function assertOwnedOutput(target, relativePath, content) {
    if (!fs.existsSync(target)) return;
    if (Buffer.isBuffer(content)) {
        if (!fs.readFileSync(target).equals(content)) fail(`Refusing to overwrite an unowned or changed media asset: ${relativePath}`);
        return;
    }
    const existing = fs.readFileSync(target, 'utf8');
    if (relativePath.endsWith('render-report.json')) {
        let report;
        try { report = JSON.parse(existing); } catch { fail('Refusing to overwrite an unowned render report'); }
        if (![GENERATOR, DESIGN_GENERATOR, UI_COMPOSITION_HTML_GENERATOR, COMPONENT_DESIGN_HTML_GENERATOR].includes(report.generator)) fail('Refusing to overwrite an unowned render report');
        return;
    }
    if (![TEXT_MARKER, UI_COMPOSITION_HTML_MARKER].some(marker => existing.includes(marker))) fail(`Refusing to overwrite an unowned generated file: ${relativePath}`);
}

function planOutputs(outputRoot, outputs) {
    return [...outputs].map(([relativePath, content]) => {
        const target = assertSafeOutputPath(outputRoot, relativePath);
        assertOwnedOutput(target, relativePath, content);
        return {target, content};
    });
}

function publishOutputs(planned) {
    for (const {target} of planned) fs.mkdirSync(path.dirname(target), {recursive: true});
    for (const {target, content} of planned) fs.writeFileSync(target, content, Buffer.isBuffer(content) ? undefined : 'utf8');
}

function countStatuses(value, status) {
    if (Array.isArray(value)) return value.reduce((total, item) => total + countStatuses(item, status), 0);
    if (!value || typeof value !== 'object') return 0;
    return (value.status === status ? 1 : 0) + Object.values(value).reduce((total, item) => total + countStatuses(item, status), 0);
}

