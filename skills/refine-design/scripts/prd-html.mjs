function iconSvg(document, iconId, label) {
    const icon = document.icons.find((candidate) => candidate.id === iconId);
    if (!icon) return '<span aria-hidden="true">?</span>';
    const geometry = iconGeometry(icon);
    if (!geometry) return '<span aria-hidden="true">?</span>';
    return `<svg viewBox="0 0 24 24" role="img" aria-label="${escapeHtml(label)}">${geometry.paths.map((item) => `<path d="${escapeHtml(item.d)}" opacity="${item.opacity}"></path>`).join('')}</svg>`;
}

function specimen(title, state, body, note = '') {
    return `<figure class="prd-state"><figcaption><strong>${escapeHtml(title)}</strong><span>${escapeHtml(state)}</span></figcaption><div class="prd-state-body">${body}</div>${note ? `<p>${escapeHtml(note)}</p>` : ''}</figure>`;
}

function renderButtonCatalog(document) {
    const button = document.button;
    const order = ['default', 'hover', 'pressed', 'focus', 'disabled', 'loading'];
    const stateSpecimens = order.filter((state) => button.states[state]).map((state) => specimen(button.label, state, `<button type="button" class="prd-button prd-button--contained prd-is-${state}"${state === 'disabled' ? ' disabled' : ''}>${state === 'loading' ? `<span class="prd-spinner" aria-hidden="true"></span>${escapeHtml(button.loadingLabel)}` : escapeHtml(button.label)}</button>`)).join('');
    const variants = [
        ['Contained', 'contained', button.label],
        ['Outlined', 'outlined', button.label],
        ['Text', 'text', button.label],
        ['Icon only', 'icon', iconSvg(document, document.buttonVariants.iconId, document.buttonVariants.accessibleLabel)],
    ];
    return `<section id="buttons" class="prd-catalog-section"><div class="prd-section-heading"><p class="rd-section-number">01</p><div><h2>Buttons</h2><p>Command states and the shared contained, outlined, text, and icon-only family.</p></div></div><div class="prd-state-grid">${stateSpecimens}</div><h3>Variants</h3><div class="prd-state-grid">${variants.map(([title, kind, content]) => specimen(title, 'default', `<button type="button" class="prd-button prd-button--${kind}"${kind === 'icon' ? ` aria-label="${escapeHtml(document.buttonVariants.accessibleLabel)}" title="${escapeHtml(document.buttonVariants.tooltip)}"` : ''}>${content}</button>`)).join('')}</div></section>`;
}

function fieldMarkup(field, state, index) {
    const inputId = `catalog-field-${state}-${index}`;
    const isError = state === 'error';
    return `<div class="prd-field prd-is-${state}"><label for="${inputId}">${escapeHtml(field.label)}</label><input id="${inputId}" value="${escapeHtml(field.value)}"${state === 'disabled' ? ' disabled' : ' readonly'}${isError ? ' aria-invalid="true" aria-describedby="catalog-field-error"' : ''}><p${isError ? ' id="catalog-field-error" class="prd-error"' : ''}>${escapeHtml(isError ? field.errorText : field.helperText)}</p></div>`;
}

