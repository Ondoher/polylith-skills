function fail(message) {
    throw new Error(message);
}

function escapeHtml(value) {
    return String(value).replace(/[&<>"']/g, (character) => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
    })[character]);
}

function sourceHash(source) {
    return createHash('sha256').update(source).digest('hex');
}

function readJson(file, label) {
    const absolute = path.resolve(file);
    let source;
    try { source = fs.readFileSync(absolute, 'utf8'); } catch { fail(`${label} is missing: ${absolute}`); }
    let value;
    try { value = JSON.parse(source); } catch { fail(`${label} is not valid JSON`); }
    return {absolute, source, value};
}

function anchor(kind, id) {
    return `${kind}-${encodeURIComponent(id)}`;
}

function idMap(records) {
    return new Map(records.map((record) => [record.id, record]));
}

function renderSiteNavigation(current, prefix = '', hasComps = false, hasComponentComps = false) {
    const items = [
        ['requirements', `${prefix}index.html`, 'Product requirements'],
        ['design-language', `${prefix}design-language/index.html`, 'Design language'],
        ['components', `${prefix}components/index.html`, 'Component states'],
        ...(hasComps ? [['comps', `${prefix}comps/index.html`, 'Product comps']] : []),
        ...(hasComponentComps ? [['component-comps', `${prefix}component-comps/index.html`, 'Component comps']] : []),
    ];
    return `<nav class="rd-site-nav" aria-label="Product requirements pages">${items.map(([id, href, label]) => id === current
        ? `<span aria-current="page">${label}</span>`
        : `<a href="${href}">${label}</a>`).join('')}</nav>`;
}

function attention(status) {
    if (status === 'locked') return '<p class="prd-attention"><strong>Locked design.</strong> Preserve this design unless the user explicitly requests a change to this scope.</p>';
    if (status === 'unresolved') return '<p class="prd-attention"><strong>Needs definition.</strong> This part of the design is still unresolved.</p>';
    if (status === 'proposed') return '<p class="prd-attention"><strong>Under consideration.</strong> This is an unselected alternative.</p>';
    return '';
}

function renderList(items, emptyText = 'None recorded.') {
    return items.length ? `<ul>${items.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}</ul>` : `<p>${escapeHtml(emptyText)}</p>`;
}

