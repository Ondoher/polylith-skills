function countPlaceholders(node) {
  if (node.kind === 'component') return node.placeholder ? 1 : 0;
  return node.children.reduce((total, child) => total + countPlaceholders(child), 0);
}

function countResolvedPlaceholders(node, templates, registrations) {
  if (node.kind === 'component') {
    if (!node.placeholder) return 0;
    const template = templates.get(node.templateRef.id);
    return componentRegistration(node, template, registrations) ? 1 : 0;
  }
  return node.children.reduce((total, child) => total + countResolvedPlaceholders(child, templates, registrations), 0);
}

export function buildUiCompositionHtml(spec, {uxSpec, designLanguage, uiSource = '', uxSource = '', designSource = '', uiLabel = 'ui/ui-spec.json', uxLabel = 'ux/ux-spec.json', designLabel = 'ui-design/design-language/design-language.json', componentRegistrations = [], assetRoot, sourceRoot, documentKind = 'composition'} = {}) {
  validateUiSpec(spec, {uxSpec, designLanguage, assetRoot, sourceRoot, documentKind});
  const templates = new Map(spec.templates.map(template => [template.id, template]));
  const placeholderCount = spec.scenes.reduce((total, scene) => total + countPlaceholders(scene.root), 0);
  const resolvedPlaceholderCount = spec.scenes.reduce((total, scene) => total + countResolvedPlaceholders(scene.root, templates, componentRegistrations), 0);
  const outputs = new Map();
  outputs.set('comps/index.html', renderCompIndex(spec, componentRegistrations));
  outputs.set('assets/composition.css', renderCompositionCss(spec));
  for (const asset of spec.assets.filter(candidate => candidate.kind === 'image')) {
    const output = imageAssetOutput(asset, assetRoot, sourceRoot);
    outputs.set(output.relative, output.bytes);
  }
  for (const request of spec.renderRequests) {
    const scene = spec.scenes.find(candidate => candidate.id === request.sceneRef);
    outputs.set(request.output, renderScenePage(scene, request, spec, uxSpec, componentRegistrations));
  }
  const reserved = new Set(['comps/index.html', 'assets/composition.css', 'ui/render-report.json']);
  for (const request of spec.renderRequests) if (reserved.has(request.output)) fail(`Render request output is reserved: ${request.output}`);
  const report = {
    generator: UI_COMPOSITION_HTML_GENERATOR,
    rendererVersion: UI_COMPOSITION_HTML_VERSION,
    sources: {
      ui: {id: spec.id, schemaVersion: spec.schemaVersion, revision: spec.revision, sha256: hash(uiSource || `${JSON.stringify(spec, null, 2)}\n`), label: uiLabel},
      ux: {id: uxSpec.id, schemaVersion: uxSpec.schemaVersion, revision: uxSpec.revision, sha256: hash(uxSource || `${JSON.stringify(uxSpec, null, 2)}\n`), label: uxLabel},
      designLanguage: {id: designLanguage.id, schemaVersion: designLanguage.schemaVersion, revision: designLanguage.revision, sha256: hash(designSource || `${JSON.stringify(designLanguage, null, 2)}\n`), label: designLabel},
    },
    outcome: spec.unspecifiedRequirements.length || spec.scenes.some(scene => scene.completeness === 'partial') ? 'partial' : 'complete',
    counts: {
      scenes: spec.scenes.length,
      renderRequests: spec.renderRequests.length,
      templates: spec.templates.length,
      placeholders: placeholderCount,
      resolvedPlaceholders: resolvedPlaceholderCount,
      unresolvedPlaceholders: placeholderCount - resolvedPlaceholderCount,
      unspecifiedRequirements: spec.unspecifiedRequirements.length,
      uxChangeRequests: spec.uxChangeRequests.length,
      deferredInteractionNodes: spec.scenes.reduce((total, scene) => total + scene.deferredInteractionNodeRefs.length, 0),
      openQuestions: spec.openQuestions.filter(question => question.status === 'open').length,
    },
    files: [...outputs.keys(), 'ui/render-report.json'].sort(),
  };
  outputs.set('ui/render-report.json', `${JSON.stringify(report, null, 2)}\n`);
  return {outputs, report};
}

function assertSafe(outputRoot, relative) {
  const root = path.resolve(outputRoot);
  const target = path.resolve(root, relative);
  if (!target.startsWith(`${root}${path.sep}`)) fail(`Output escapes destination: ${relative}`);
  if (fs.existsSync(root) && fs.lstatSync(root).isSymbolicLink()) fail(`Refusing linked output root: ${root}`);
  let current = root;
  for (const part of path.relative(root, target).split(path.sep).slice(0, -1)) {
    current = path.join(current, part);
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) fail(`Refusing linked output path: ${current}`);
  }
  if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) fail(`Refusing linked output file: ${target}`);
  return target;
}

function assertOwned(target, relative, content) {
  if (!fs.existsSync(target)) return;
  if (Buffer.isBuffer(content)) {
    if (!fs.readFileSync(target).equals(content)) fail(`Refusing to overwrite an unowned or changed media asset: ${relative}`);
    return;
  }
  const existing = fs.readFileSync(target, 'utf8');
  if (relative.endsWith('render-report.json')) {
    let report;
    try { report = JSON.parse(existing); } catch { fail(`Refusing to overwrite unowned report: ${relative}`); }
    if (report.generator !== UI_COMPOSITION_HTML_GENERATOR) fail(`Refusing to overwrite unowned report: ${relative}`);
  } else if (!existing.includes(UI_COMPOSITION_HTML_MARKER)) {
    fail(`Refusing to overwrite unowned generated file: ${relative}`);
  }
}

export function publishUiCompositionHtml(uiFile, uxFile, designFile, outputRoot, options = {}) {
  const ui = readJson(uiFile, 'UI composition source');
  const ux = readJson(uxFile, 'UX source');
  const design = readJson(designFile, 'Design-language source');
  if (!options.sourceRoot) fail('UI composition HTML publication requires an explicit sourceRoot');
  const authorized = authorizeAssetRoot(
    options.assetRoot ?? path.dirname(ui.absolute),
    options.sourceRoot,
    'UI assetRoot',
  );
  const built = buildUiCompositionHtml(ui.value, {
    uxSpec: ux.value,
    designLanguage: design.value,
    uiSource: ui.source,
    uxSource: ux.source,
    designSource: design.source,
    assetRoot: authorized.assetRoot,
    sourceRoot: authorized.sourceRoot,
    uiLabel: options.uiLabel ?? path.basename(ui.absolute),
    uxLabel: options.uxLabel ?? path.basename(ux.absolute),
    designLabel: options.designLabel ?? path.basename(design.absolute),
  });
  const planned = [...built.outputs].map(([relative, content]) => {
    const target = assertSafe(outputRoot, relative);
    assertOwned(target, relative, content);
    return {target, content};
  });
  for (const item of planned) fs.mkdirSync(path.dirname(item.target), {recursive: true});
  for (const item of planned) fs.writeFileSync(item.target, item.content, Buffer.isBuffer(item.content) ? undefined : 'utf8');
  return {...built.report, outputRoot: path.resolve(outputRoot)};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [ui, ux, design, output, ...args] = process.argv.slice(2);
    if (!ui || !ux || !design || !output) fail('Usage: node ui-composition-html.mjs <ui-spec.json> <ux-spec.json> <design-language.json> <prd-output-root> --source-root <authoritative-source-root> [--asset-root <ui-asset-root>] [--ui-label <label>] [--ux-label <label>] [--design-label <label>]');
    const options = {};
    for (let index = 0; index < args.length; index += 2) {
      const flag = args[index], value = args[index + 1];
      if (!value) fail(`Missing value for ${flag}`);
      if (flag === '--ui-label') options.uiLabel = value;
      else if (flag === '--ux-label') options.uxLabel = value;
      else if (flag === '--design-label') options.designLabel = value;
      else if (flag === '--asset-root') options.assetRoot = path.resolve(value);
      else if (flag === '--source-root') options.sourceRoot = path.resolve(value);
      else fail(`Unknown option: ${flag}`);
    }
    if (!options.sourceRoot) fail('UI composition HTML publication requires --source-root');
    process.stdout.write(`${JSON.stringify(publishUiCompositionHtml(ui, ux, design, output, options), null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
