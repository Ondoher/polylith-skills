function fail(message) {
  throw new Error(message);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  })[character]);
}

function cssIdentifier(value) {
  return String(value).replace(/[^a-z0-9_-]/gi, '-').replace(/^-+/, '') || 'value';
}

function hash(value) {
  return createHash('sha256').update(value).digest('hex');
}

function imageAssetRelative(asset) {
  const safeName = path.basename(asset.path).replace(/[^a-z0-9._-]/gi, '-');
  return `assets/ui-media/${asset.sha256.slice(0, 12)}-${safeName}`;
}

function imageAssetOutput(asset, assetRoot, sourceRoot) {
  const {bytes} = loadUiImageAsset(asset, assetRoot, sourceRoot);
  return {relative: imageAssetRelative(asset), bytes};
}

function relativeHref(fromFile, toFile) {
  const relative = path.posix.relative(path.posix.dirname(fromFile), toFile);
  return relative || path.posix.basename(toFile);
}

function readJson(file, label) {
  const absolute = path.resolve(file);
  let source;
  try { source = fs.readFileSync(absolute, 'utf8'); } catch { fail(`${label} is missing: ${absolute}`); }
  let value;
  try { value = JSON.parse(source); } catch { fail(`${label} is not valid JSON`); }
  return {absolute, source, value};
}

function metricCss(value, tokens) {
  if (typeof value === 'number') return `${value}px`;
  if (!tokens.has(value.tokenRef)) fail(`Missing rendered token ${value.tokenRef}`);
  return `var(--ui-token-${cssIdentifier(value.tokenRef)})`;
}

function paddingCss(value, tokens) {
  if (typeof value === 'number' || value?.tokenRef) return metricCss(value, tokens);
  return ['top', 'right', 'bottom', 'left'].map(edge => metricCss(value[edge], tokens)).join(' ');
}

function trackCss(track) {
  if (track.unit === 'content') return 'max-content';
  return `${track.value}${track.unit}`;
}

function declarations(values) {
  return Object.entries(values).filter(([, value]) => value !== undefined && value !== '').map(([key, value]) => `${key}:${value}`).join(';');
}

function layoutStyle(layout, tokens) {
  const result = {
    display: layout.mode,
    gap: metricCss(layout.gap, tokens),
    padding: paddingCss(layout.padding, tokens),
    'align-items': layout.align,
    'justify-content': layout.justify,
  };
  if (layout.mode === 'grid') {
    result['grid-template-columns'] = layout.columns.map(trackCss).join(' ');
    result['grid-template-rows'] = layout.rows.map(trackCss).join(' ');
  } else {
    result['flex-direction'] = layout.direction;
    result['flex-wrap'] = layout.wrap ? 'wrap' : 'nowrap';
  }
  return declarations(result);
}

function nodeStyle(node, template, tokens) {
  const result = {};
  if (node.placement) {
    if (node.placement.row) result['grid-row'] = `${node.placement.row} / span ${node.placement.rowSpan ?? 1}`;
    if (node.placement.column) result['grid-column'] = `${node.placement.column} / span ${node.placement.columnSpan ?? 1}`;
  }
  const constraints = node.constraints ?? template?.sizing ?? {};
  for (const [source, target] of [['minWidthPx', 'min-width'], ['maxWidthPx', 'max-width'], ['minHeightPx', 'min-height'], ['maxHeightPx', 'max-height']]) {
    if (constraints[source] !== undefined) result[target] = `${constraints[source]}px`;
  }
  if (template?.sizing?.width === 'fixed') result.width = `${template.sizing.widthPx}px`;
  if (template?.sizing?.width === 'fill') result.width = '100%';
  if (template?.sizing?.height === 'fixed') result.height = `${template.sizing.heightPx}px`;
  if (template?.sizing?.height === 'fill') result.height = '100%';
  return declarations(result);
}

function sourceClasses(node) {
  return (node.styleRefs ?? []).map(reference => `ui-${reference.kind}--${cssIdentifier(reference.id)}`).join(' ');
}

function metricLabel(value, tokens) {
  if (typeof value === 'number') return `${value}px`;
  if (value?.tokenRef) return `${tokens.get(value.tokenRef).value}px`;
  return ['top', 'right', 'bottom', 'left'].map(edge => metricLabel(value[edge], tokens)).join('/');
}

function annotationAttributes(node, templateId, label) {
  const parts = [
    `data-ui-node="${escapeHtml(node.id)}"`,
    `data-ui-state="${escapeHtml(node.state ?? 'layout')}"`,
    `data-ui-annotation="${escapeHtml(label)}"`,
  ];
  if (templateId) parts.push(`data-ui-template="${escapeHtml(templateId)}"`);
  return parts.join(' ');
}

function componentRegistration(node, template, registrations) {
  return registrations.find(registration =>
    registration.replacesTemplateRef.id === template.id &&
    registration.replacesTemplateRef.version === template.version &&
    registration.stateOutputs[node.state]
  );
}

function renderTemplate(node, template, context) {
  const parameters = node.parameters;
  const element = template.html.element;
  const text = parameters.text ?? parameters.label ?? '';
  const compact = template.html.renderer === 'placeholder' && template.sizing.height === 'fixed' && template.sizing.heightPx <= 64 ? 'ui-placeholder-compact' : '';
  const classes = `ui-template ${template.html.className} ${compact} ui-is-${cssIdentifier(node.state)} ${sourceClasses(node)}`.trim();
  const common = `class="${escapeHtml(classes)}"`;
  if (template.html.renderer === 'heading' || template.html.renderer === 'text' || template.html.renderer === 'status') {
    return `<${element} ${common}>${escapeHtml(text)}</${element}>`;
  }
  if (template.html.renderer === 'button') {
    const disabled = node.state === 'disabled' || parameters.disabled === true ? ' disabled' : '';
    return `<button type="button" ${common}${disabled}>${escapeHtml(parameters.label)}</button>`;
  }
  if (template.html.renderer === 'icon-button') {
    const label = parameters.accessibleLabel ?? parameters.label;
    return `<button type="button" ${common} aria-label="${escapeHtml(label)}" title="${escapeHtml(parameters.tooltip ?? label)}"><span aria-hidden="true">${escapeHtml(parameters.glyph ?? '•')}</span></button>`;
  }
  if (template.html.renderer === 'text-field') {
    const inputId = `ui-field-${cssIdentifier(node.id)}`;
    const helperId = `${inputId}-helper`;
    const disabled = node.state === 'disabled' || parameters.disabled === true ? ' disabled' : '';
    return `<div ${common}><label for="${inputId}">${escapeHtml(parameters.label)}</label><input id="${inputId}" value="${escapeHtml(parameters.value ?? '')}" readonly${disabled}${parameters.helperText ? ` aria-describedby="${helperId}"` : ''}>${parameters.helperText ? `<p id="${helperId}">${escapeHtml(parameters.helperText)}</p>` : ''}</div>`;
  }
  if (template.html.renderer === 'choice-group') {
    const label = parameters.label;
    const disabled = parameters.disabled === true;
    const options = parameters.options;
    if (parameters.presentation === 'select') {
      const inputId = `ui-choice-${cssIdentifier(node.id)}`;
      const rendered = options.map(option => `<option${option.id === parameters.selectedId ? ' selected' : ''}${disabled || option.disabled ? ' disabled' : ''}>${escapeHtml(option.label)}</option>`).join('');
      return `<div ${common} data-presentation="select"><label for="${inputId}">${escapeHtml(label)}</label><select id="${inputId}"${disabled ? ' disabled' : ''}>${rendered}</select></div>`;
    }
    if (parameters.presentation === 'tabs') {
      const rendered = options.map(option => `<button type="button" role="tab" aria-selected="${option.id === parameters.selectedId ? 'true' : 'false'}"${disabled || option.disabled ? ' disabled' : ''}><span>${escapeHtml(option.label)}</span>${option.secondary ? `<small>${escapeHtml(option.secondary)}</small>` : ''}</button>`).join('');
      return `<${element} ${common} role="tablist" aria-label="${escapeHtml(label)}" data-presentation="tabs">${rendered}</${element}>`;
    }
    let activeGroup;
    const rendered = options.map(option => {
      const optionHtml = `<div role="option" aria-selected="${option.id === parameters.selectedId ? 'true' : 'false'}"${disabled || option.disabled ? ' aria-disabled="true"' : ''}><span>${escapeHtml(option.label)}</span>${option.secondary ? `<small>${escapeHtml(option.secondary)}</small>` : ''}</div>`;
      if (option.group === undefined) {
        activeGroup = undefined;
        return optionHtml;
      }
      if (option.group === activeGroup) return optionHtml;
      activeGroup = option.group;
      return `<div class="ui-choice-group__heading" role="presentation">${escapeHtml(option.group)}</div>${optionHtml}`;
    }).join('');
    return `<${element} ${common} role="listbox" aria-label="${escapeHtml(label)}" data-presentation="list">${rendered}</${element}>`;
  }
  if (template.html.renderer === 'image') {
    const asset = context.assets.get(parameters.assetId);
    const source = relativeHref(context.request.output, imageAssetRelative(asset));
    const imageStyle = declarations({
      'object-fit': parameters.fitMode,
      transform: `translate(${parameters.offsetX ?? 0}px,${parameters.offsetY ?? 0}px) scale(${parameters.scale ?? 1})`,
    });
    return `<div ${common} role="img" aria-label="${escapeHtml(parameters.accessibleLabel)}"><img src="${escapeHtml(source)}" alt="" width="${asset.widthPx}" height="${asset.heightPx}" style="${escapeHtml(imageStyle)}"></div>`;
  }
  if (template.html.renderer === 'visual') {
    const accessibleLabel = parameters.accessibleLabel ?? parameters.text;
    const label = accessibleLabel ? ` aria-label="${escapeHtml(accessibleLabel)}"` : ' aria-hidden="true"';
    const roleClass = `ui-visual--${cssIdentifier(parameters.role)}`;
    const variantClass = parameters.variant ? ` ui-visual-variant--${cssIdentifier(parameters.variant)}` : '';
    return `<${element} class="${escapeHtml(`${classes} ${roleClass}${variantClass}`)}"${label}>${parameters.text ? escapeHtml(parameters.text) : ''}</${element}>`;
  }
  if (template.html.renderer === 'placeholder') {
    const registration = componentRegistration(node, template, context.componentRegistrations);
    if (registration) {
      if (registration.inlineSpec) {
        const mapping = registration.inlineSpec.componentTemplate.stateScenes.find(candidate => candidate.state === node.state);
        const scene = registration.inlineSpec.scenes.find(candidate => candidate.id === mapping.sceneRef);
        const content = renderSceneTree(scene, registration.inlineSpec, context.uxSpec, {
          request: context.request,
          componentRegistrations: context.componentRegistrations,
          uxSpec: context.uxSpec,
        });
        const role = registration.accessibility?.role ?? 'group';
        const name = registration.accessibility?.name ?? `${registration.name} ${node.state}`;
        return `<div class="ui-complex-component" role="${escapeHtml(role)}" aria-label="${escapeHtml(name)}">${content}</div>`;
      }
      const output = registration.stateOutputs[node.state];
      const source = `${relativeHref(context.request.output, output)}#scene`;
      return `<iframe class="ui-complex-component" src="${escapeHtml(source)}" title="${escapeHtml(`${registration.name} ${node.state}`)}" loading="lazy"></iframe>`;
    }
    return `<section ${common} role="img" aria-label="${escapeHtml(node.placeholder.label)}"><strong>${escapeHtml(node.placeholder.label)}</strong><p>${escapeHtml(node.placeholder.description)}</p>${parameters.detail ? `<small>${escapeHtml(parameters.detail)}</small>` : ''}</section>`;
  }
  fail(`Unsupported HTML renderer ${template.html.renderer}`);
}

function renderSceneTree(scene, spec, uxSpec, context) {
  const tokens = new Map(spec.tokens.map(token => [token.id, token]));
  const templates = new Map(spec.templates.map(template => [template.id, template]));
  const surface = uxSpec.surfaces.find(candidate => candidate.id === scene.surfaceRef);
  const regions = new Map(surface.regions.map(region => [region.id, region]));
  context.assets = new Map(spec.assets.map(asset => [asset.id, asset]));
  const renderNode = (node, root = false) => {
    if (node.kind === 'region') {
      const uxRegion = node.uxRegionRef ? regions.get(node.uxRegionRef) : null;
      const label = node.label ?? uxRegion?.name ?? (root ? scene.name : node.id);
      const surfaceClass = node.surfaceTreatment ? `ui-surface-${cssIdentifier(node.surfaceTreatment)}` : '';
      const classes = `${root ? 'ui-scene-root' : 'ui-region'} ${surfaceClass} ${sourceClasses(node)}`.trim();
      const style = [layoutStyle(node.layout, tokens), nodeStyle(node, null, tokens)].filter(Boolean).join(';');
      const children = node.children.map(child => renderNode(child)).join('');
      const element = root && scene.transientBehavior?.presentation === 'dialog' ? 'dialog' : (root ? 'div' : 'section');
      const transientAttributes = root && scene.transientBehavior
        ? ` data-ui-transient="${escapeHtml(scene.transientBehavior.presentation)}"${element === 'dialog' ? ' open aria-modal="true"' : ''}`
        : '';
      const tracks = node.layout.mode === 'grid' ? ` · ${node.layout.columns.length}c×${node.layout.rows.length}r` : '';
      const measurement = `padding ${metricLabel(node.layout.padding, tokens)} · gap ${metricLabel(node.layout.gap, tokens)}${tracks}`;
      return `<${element} class="${escapeHtml(classes)}" aria-label="${escapeHtml(label)}" ${annotationAttributes(node, null, `${label} · ${node.layout.mode}`)} data-ui-measurement="${escapeHtml(measurement)}"${transientAttributes}${style ? ` style="${escapeHtml(style)}"` : ''}>${children}</${element}>`;
    }
    const template = templates.get(node.templateRef.id);
    const label = template.html.renderer === 'visual'
      ? `${node.parameters.accessibleLabel ?? node.parameters.text ?? node.parameters.role} · ${node.parameters.role}`
      : `${template.name} · ${node.state}`;
    const style = nodeStyle(node, template, tokens);
    return `<div class="ui-node-frame" ${annotationAttributes(node, template.id, label)}${style ? ` style="${escapeHtml(style)}"` : ''}>${renderTemplate(node, template, context)}</div>`;
  };
  return renderNode(scene.root, true);
}

/** Render one clean scene directly into a containing document without an iframe or review-page chrome. */
export function renderInlineScene(scene, spec, {uxSpec, componentRegistrations = []} = {}) {
  const sceneMarkup = renderSceneTree(scene, spec, uxSpec, {
    request: {output: 'index.html', variant: 'clean'},
    componentRegistrations,
    uxSpec,
  });
  return `<div class="prd-comp-canvas ui-viewport" style="--ui-viewport-width:${scene.viewport.width}px;--ui-viewport-height:${scene.viewport.height}px" data-ui-scene="${escapeHtml(scene.id)}" data-ui-source-revisions="${escapeHtml(`${spec.uxSource.revision}/${spec.designLanguageSource.revision}`)}">${sceneMarkup}</div>`;
}

function pageNavigation(scene, request, requestsForScene, artifactKind) {
  const clean = requestsForScene.find(candidate => candidate.variant === 'clean');
  const annotated = requestsForScene.find(candidate => candidate.variant === 'annotated');
  const item = (candidate, label) => candidate.id === request.id
    ? `<span aria-current="page">${label}</span>`
    : `<a href="${escapeHtml(path.posix.basename(candidate.output))}">${label}</a>`;
  return `<nav class="ui-review-nav" aria-label="UI review pages"><a href="../index.html">Product requirements</a><a href="../design-language/index.html">Design language</a><a href="../components/index.html">Component states</a><a href="index.html">Product UI</a>${item(clean, `Clean ${artifactKind}`)}${item(annotated, `Annotated ${artifactKind}`)}</nav>`;
}

